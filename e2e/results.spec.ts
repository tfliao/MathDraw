import { expect, test } from '@playwright/test'
import { imageFile } from './fixtures'

test('impossible settings explain the conflict and recover into a zero-only puzzle', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('1. Choose a picture').setInputFiles(await imageFile(page))
  await page.getByText('Advanced', { exact: true }).click()
  await page.getByLabel('Maximum result', { exact: true }).fill('1')
  const error = page.getByText('These math settings produce no allowed answers.', { exact: false })
  await expect(error).toBeVisible()
  await expect(page.getByRole('button', { name: 'Create puzzle' })).toBeDisabled()
  await page.getByLabel('Maximum result', { exact: true }).fill('0')
  await page.getByLabel('Allow zero results').check()
  await expect(error).toBeVisible()
  await page.getByLabel('Addition (+)', { exact: true }).uncheck()
  await page.getByLabel('Subtraction (-)', { exact: true }).check()
  await page.getByLabel('Multiple results per color').check()
  await expect(error).toHaveCount(0)
  await expect(page.getByText('These math settings provide 1 distinct answers', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Create puzzle' }).click()
  const key = page.locator('.app-shell .color-key td')
  await expect(key).toHaveCount(1)
  await expect(key).toHaveAttribute('data-results', '0')
  const expressions = await page.locator('.app-shell .math-grid td').allTextContents()
  expect(expressions.every(text => /^[1-9]-[1-9]$/.test(text) && text[0] === text[2])).toBe(true)
  await page.getByLabel('Allow zero results').uncheck()
  await expect(error).toBeVisible()
  await expect(page.getByRole('button', { name: 'Print puzzle', exact: true })).toBeDisabled()
  await page.getByText('Advanced', { exact: true }).click()
  await expect(error).toBeVisible()
  await expect(page.getByRole('button', { name: 'Create puzzle' })).toBeDisabled()
})

test('zero operands remain legal while zero results are excluded', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('1. Choose a picture').setInputFiles(await imageFile(page))
  await page.getByText('Advanced', { exact: true }).click()
  await page.getByLabel('Allow zero operands').check()
  await page.getByLabel('Maximum result', { exact: true }).fill('1')
  await page.getByLabel('Multiple results per color').check()
  await page.getByRole('button', { name: 'Create puzzle' }).click()
  await expect(page.locator('.app-shell .color-key td')).toHaveAttribute('data-results', '1')
  const expressions = await page.locator('.app-shell .math-grid td').allTextContents()
  expect(expressions.every(text => text === '0+1' || text === '1+0')).toBe(true)
})

test('result cap filters mixed-operator keys before multi-map and palette generation', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('1. Choose a picture').setInputFiles(await imageFile(page, { palette: true }))
  await page.getByText('Advanced', { exact: true }).click()
  await page.getByLabel('Subtraction (-)', { exact: true }).check()
  await page.getByLabel('Multiplication (\u00d7)', { exact: true }).check()
  await page.getByLabel('Maximum colors', { exact: true }).fill('16')
  await page.getByLabel('Maximum result', { exact: true }).fill('3')
  await page.getByLabel('Multiple results per color').check()
  await expect(page.getByText('These math settings provide 3 distinct answers', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Create puzzle' }).click()
  await expect(page.locator('.app-shell .color-key td')).toHaveCount(3)
  const problems = await page.locator('.app-shell .math-grid td').allTextContents()
  const results = problems.map(text => {
    const match = /^(\d+)([+\u00d7-])(\d+)$/.exec(text)!
    const a = Number(match[1]), b = Number(match[3])
    return match[2] === '+' ? a + b : match[2] === '-' ? a - b : a * b
  })
  expect(new Set(results)).toEqual(new Set([1, 2, 3]))
  await expect(page.locator('.app-shell .worksheet')).not.toContainText('*')
})
